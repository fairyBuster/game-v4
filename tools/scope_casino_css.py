"""Scope Casino-App's global.css under .casino-shell so it can live inside the DY01 app.

Their stylesheet is an app-wide one (.btn, .panel, .badge, .muted...), which collides with
dy01-clone's own UI classes. Every selector gets a `.casino-shell` prefix; @keyframes/@font-face
stay untouched, @media bodies are scoped recursively.

    python tools/scope_casino_css.py [src] [dst]
"""
import re
import sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else
           r"C:\Users\user\Downloads\Xaxino v3.8 Nulled\Casino-App\frontend\src\styles\global.css")
DST = Path(sys.argv[2] if len(sys.argv) > 2 else
           r"C:\Project\dy01-clone\web\src\games\casino.css")
PREFIX = ".casino-shell"


PAGE_LEVEL = ("html", "body", "#root")


def scope_selectors(sel: str) -> str:
    parts = [p.strip() for p in re.split(r",(?![^(]*\))", sel) if p.strip()]
    out = []
    for p in parts:
        head = re.split(r"[\s.:#\[]", p, 1)[0]
        if head in PAGE_LEVEL:
            continue                      # page-level rules (min-height:100vh, body bg) would break our stage
        if p == "*":
            out.append(PREFIX + " *")
        elif p.startswith(":root"):
            out.append(PREFIX + p[len(":root"):])
        else:
            out.append(f"{PREFIX} {p}")
    return ", ".join(out)


def scope(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)     # comments would end up in selector lists
    css = css.replace("/assets/", "/casino/")           # their asset paths, our public dir
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j == -1:
            out.append(css[i:])
            break
        prelude = css[i:j]
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == "{":
                depth += 1
            elif css[k] == "}":
                depth -= 1
            k += 1
        body = css[j + 1:k - 1]
        head = prelude.strip()
        if head.startswith("@media") or head.startswith("@supports"):
            out.append(f"{prelude}{{{scope(body)}}}")
        elif head.startswith("@"):
            out.append(f"{prelude}{{{body}}}")          # @keyframes / @font-face: as-is
        else:
            sel = scope_selectors(head)
            if sel:
                out.append(f"\n{sel} {{{body}}}")
        i = k
    return "".join(out)


